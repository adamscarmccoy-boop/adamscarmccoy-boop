"""Unified Llama & LM Studio Runner supporting llama.exe CLI, llama-server, and LM Studio endpoints."""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import urllib.error
import urllib.request
from typing import Any, Dict, Optional, Union


def query_openai_api(
    base_url: str,
    prompt: str,
    model: str = "default",
    api_key: str = "lm-studio",
    system_prompt: str = "You are a high-performance local AI assistant.",
    temperature: float = 0.2,
    timeout: float = 60.0,
) -> str:
    """Queries an OpenAI-compatible HTTP endpoint (LM Studio or llama-server)."""
    endpoint = base_url.rstrip("/") + "/chat/completions"
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": prompt},
        ],
        "temperature": temperature,
    }

    req = urllib.request.Request(
        endpoint,
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            return data["choices"][0]["message"]["content"]
    except (urllib.error.HTTPError, urllib.error.URLError, KeyError, IndexError) as err:
        raise RuntimeError(f"Error calling OpenAI API at {endpoint}: {err}") from err


def run_llama_cli(
    executable_path: str,
    model_path: str,
    prompt: str,
    n_predict: int = 128,
    extra_args: Optional[list[str]] = None,
) -> str:
    """Executes a local llama.exe CLI binary directly.

    Args:
        executable_path: Path to llama.exe or llama-cli executable.
        model_path: Path to model GGUF file.
        prompt: User input prompt.
        n_predict: Number of tokens to predict.
        extra_args: Optional extra command-line flags.

    Returns:
        Standard output text generated by llama.exe.
    """
    exec_norm = os.path.normpath(executable_path)
    model_norm = os.path.normpath(model_path)

    cmd = [exec_norm, "-m", model_norm, "-p", prompt, "-n", str(n_predict)]
    if extra_args:
        cmd.extend(extra_args)

    try:
        res = subprocess.run(cmd, capture_output=True, text=True, check=True)
        return res.stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError) as err:
        raise RuntimeError(f"Failed to execute llama CLI binary ({exec_norm}): {err}") from err


class UnifiedLlamaRunner:
    """Unified engine to route requests between local binaries, llama-server, or LM Studio."""

    def __init__(
        self,
        mode: str = "lm_studio",
        base_url: str = "http://127.0.0.1:1234/v1",
        api_key: str = "lm-studio",
        model_name: str = "default",
        llama_exe_path: Optional[str] = None,
        gguf_model_path: Optional[str] = None,
    ):
        self.mode = mode.lower()
        self.base_url = base_url
        self.api_key = api_key
        self.model_name = model_name
        self.llama_exe_path = llama_exe_path
        self.gguf_model_path = gguf_model_path

    def generate(self, prompt: str, system_prompt: Optional[str] = None) -> str:
        if self.mode in ("lm_studio", "llama_server"):
            sys_p = system_prompt or "You are a local AI assistant."
            return query_openai_api(
                base_url=self.base_url,
                prompt=prompt,
                model=self.model_name,
                api_key=self.api_key,
                system_prompt=sys_p,
            )
        elif self.mode in ("llama_exe", "cli"):
            if not self.llama_exe_path or not self.gguf_model_path:
                raise ValueError("llama_exe_path and gguf_model_path required for CLI mode.")
            return run_llama_cli(
                executable_path=self.llama_exe_path,
                model_path=self.gguf_model_path,
                prompt=prompt,
            )
        else:
            raise ValueError(f"Unsupported execution mode: {self.mode}")
